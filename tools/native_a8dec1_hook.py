#!/usr/bin/env python3
"""[GT6 0174] The vertex loop of SPU job module a8dec1 (LS 0x6750: per vertex a call of the transform at 0x46A8,
which calls the sine / cosine at 0x76B0 twice, then one outcode byte) fused into one native function, generated from
the module's own lifted code - the lifted code is not in this file.

  native_a8dec1_hook.py            apply (idempotent)
  native_a8dec1_hook.py --check    read-only: hooked or not
  native_a8dec1_hook.py --restore  take it out again

What the fused function is: the lifted statements of every block of the loop and of both callees, in the same order,
with the SPU registers in local variables instead of ctx->gpr (written back once, at the loop's exit), every block
transfer (SPU_DIRECT) a goto, every call inlined (its return a goto back to the call site) - so the same helper calls
(the same SPU float semantics, the same local-store reads and writes in the same order) on the same values: the same
results, without about 45 block transfers and three call brackets a vertex. Statements that touch the context in any
other way stop the generation. The blocks are found by following the transfers from the loop's entry; the module
counts only when their lifted bodies (in address order, the module's name written as "@") have the SHA-256 below -
the reviewed ones. gt6_native_a8dec1.c decides at run time whether the fused loop may run (gt6_native_a8dec1_gate);
when it may not, the lifted loop runs as before. spu_jobs/*/spu_recomp.c are generated (ps3recomp/tools/
lift_jobmods.py); after a new lift run this again.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOD = "jobmod_a8dec1c06729_e0030"
LOOP, EXIT = 0x6750, 0x6840
BODY_SHA256 = "19a4d412559c6cfa400a670fb14faa0a692d34f28f9217b31dbfa38a31f648b6"
BEGIN = "/* GT6_NATIVE_A8DEC1 begin ([GT6 0174], generated by tools/native_a8dec1_hook.py) */\n"
END = "/* GT6_NATIVE_A8DEC1 end */\n"
GUARD = "#if defined(SPU_CALL_FAST_PATH) && defined(SPU_DIRECT_TAILCALLS)\n"
HOOK = (GUARD +
        "        if (gt6_native_a8dec1_gate(ctx, a8dec1_fused_pcs, A8DEC1_FUSED_NPCS)) {"
        " a8dec1_fused_6750(ctx); SPU_DIRECT(ctx, 0x%X, @_spu_func_%08X); }   /* GT6_NATIVE_A8DEC1 */\n"
        "#endif\n") % (EXIT, EXIT)

FUNC_RE = re.compile(r"^void (\w+)_spu_func_([0-9A-F]{8})\(spu_context\* ctx\) \{\n", re.M)
DIRECT_RE = re.compile(r"^\{ SPU_DIRECT\(ctx, 0x([0-9A-Fa-f]+), \w+\); \}$")
IF_DIRECT_RE = re.compile(r"^if \((.*)\) \{ SPU_DIRECT\(ctx, 0x([0-9A-Fa-f]+), \w+\); \}$")
IF_GOTO_RE = re.compile(r"^if \((.*)\) goto (loc_[0-9A-F]{8});$")
LABEL_RE = re.compile(r"^(loc_[0-9A-F]{8}):$")
CALL_RE = re.compile(r"^ctx->gpr\[0\] = spu_link\(0x([0-9A-Fa-f]+)\); \{ int32_t _si = \(int32_t\)ctx->image_id; "
                     r"ctx->host_depth\+\+; (\w+)_spu_func_([0-9A-F]{8})\(ctx\); spu_drain_call\(ctx, 0x\1\); "
                     r"ctx->host_depth--; spu_img_restore\(ctx, _si\); \}$")
GPR_RE = re.compile(r"ctx->gpr\[(\d+)\]")
SKIP = {"/* nop */;", "/* branch hint (ignored) */;", ""}


def functions(text: str, mod: str) -> dict[int, tuple[int, int, str]]:
    """pc -> (start of the function, end, its body lines) for every lifted function of the module"""
    out = {}
    for m in FUNC_RE.finditer(text):
        if m.group(1) == mod:
            end = text.index("\n}\n", m.end())
            out[int(m.group(2), 16)] = (m.start(), end + 3, text[m.end():end + 1])
    return out


def targets(body: str) -> list[int]:
    out = []
    for raw in body.splitlines():
        s = raw.strip()
        m = DIRECT_RE.match(s) or IF_DIRECT_RE.match(s)
        if m:
            out.append(int(m.groups()[-1], 16))
    return out


def closure(funcs: dict, entry: int, stop: set[int]) -> set[int]:
    seen: set[int] = set()
    todo = [entry]
    while todo:
        pc = todo.pop()
        if pc in seen or pc in stop:
            continue
        if pc not in funcs:
            raise SystemExit("block 0x%X is not a lifted function" % pc)
        seen.add(pc)
        todo.extend(targets(funcs[pc][2]))
    return seen


class Gen:
    def __init__(self, funcs: dict, mod: str):
        self.funcs, self.mod = funcs, mod
        self.sites = 0
        self.regs: set[int] = set()
        self.pcs: set[int] = set()
        self.lines: list[str] = []

    def expr(self, s: str) -> str:
        for n in GPR_RE.findall(s):
            self.regs.add(int(n))
        s = GPR_RE.sub(lambda m: "r" + m.group(1), s)
        rest = s.replace("spu_ls_read128(ctx, ", "").replace("spu_ls_write128(ctx, ", "")
        if re.search(r"\bctx\b", rest):
            raise SystemExit("a statement touches the context: " + s)
        return s

    def proc(self, entry: int, prefix: str, ret: str | None, stop: set[int]) -> None:
        blocks = closure(self.funcs, entry, stop)
        self.pcs |= blocks
        for pc in [entry] + sorted(blocks - {entry}):
            self.lines.append("%s_%05X:;" % (prefix, pc))
            for raw in self.funcs[pc][2].splitlines():
                self.stmt(raw.strip(), prefix, ret, blocks, stop)

    def jump(self, t: int, prefix: str, blocks: set[int], stop: set[int]) -> str:
        if t in blocks:
            return "goto %s_%05X;" % (prefix, t)
        if t in stop:
            return "goto L_exit;"
        raise SystemExit("a transfer to 0x%X leaves the fused blocks" % t)

    def stmt(self, s: str, prefix: str, ret: str | None, blocks: set[int], stop: set[int]) -> None:
        if s in SKIP:
            return
        m = DIRECT_RE.match(s)
        if m:
            self.lines.append(self.jump(int(m.group(1), 16), prefix, blocks, stop))
            return
        m = IF_DIRECT_RE.match(s)
        if m:
            self.lines.append("if (%s) %s" % (self.expr(m.group(1)), self.jump(int(m.group(2), 16), prefix, blocks, stop)))
            return
        m = IF_GOTO_RE.match(s)
        if m:
            self.lines.append("if (%s) goto %s_%s;" % (self.expr(m.group(1)), prefix, m.group(2)))
            return
        m = LABEL_RE.match(s)
        if m:
            self.lines.append("%s_%s:;" % (prefix, m.group(1)))
            return
        if s == "SPU_RET(ctx);":
            if ret is None:
                raise SystemExit("a return out of the loop itself")
            self.lines.append("goto %s;" % ret)
            return
        m = CALL_RE.match(s)
        if m:
            if m.group(2) != self.mod:
                raise SystemExit("a call into another module: " + s)
            self.sites += 1
            site = "C%d" % self.sites
            self.regs.add(0)
            self.lines.append("r0 = spu_link(0x%s);" % m.group(1))
            self.lines.append("goto %s_%05X;" % (site, int(m.group(3), 16)))
            self.proc(int(m.group(3), 16), site, site + "_ret", set())
            self.lines.append("%s_ret:;" % site)
            return
        if not s.endswith(";") or "SPU_" in s or "goto" in s or s.startswith("{") or s.startswith("if"):
            raise SystemExit("a statement the generator does not know: " + s)
        self.lines.append(self.expr(s))


def fused_set(funcs: dict) -> set[int]:
    """every lifted function the fused code is made of: the loop's blocks and, through the calls, the callees'"""
    out: set[int] = set()
    todo = [(LOOP, {EXIT})]
    while todo:
        entry, stop = todo.pop()
        for pc in closure(funcs, entry, stop):
            if pc in out:
                continue
            out.add(pc)
            for raw in funcs[pc][2].splitlines():
                m = CALL_RE.match(raw.strip())
                if m:
                    todo.append((int(m.group(3), 16), set()))
    return out


def body_hash(funcs: dict, mod: str, hooked_head: str) -> str:
    h = hashlib.sha256()
    for pc in sorted(fused_set(funcs)):
        body = funcs[pc][2]
        if pc == LOOP and body.startswith(hooked_head):
            body = body[len(hooked_head):]
        h.update(body.replace(mod, "@").encode())
    return h.hexdigest()


def generate(funcs: dict, mod: str) -> str:
    g = Gen(funcs, mod)
    g.proc(LOOP, "L", None, {EXIT})
    pcs = sorted(g.pcs)
    regs = sorted(g.regs)
    out = [BEGIN, GUARD,
           "int gt6_native_a8dec1_gate(spu_context* ctx, const uint32_t* pcs, unsigned npcs);   /* gt6_native_a8dec1.c */\n",
           "#define A8DEC1_FUSED_NPCS %du\n" % len(pcs),
           "static const uint32_t a8dec1_fused_pcs[A8DEC1_FUSED_NPCS] = {\n"]
    for i in range(0, len(pcs), 10):
        out.append("    " + ", ".join("0x%X" % p for p in pcs[i:i + 10]) + ",\n")
    out.append("};\n")
    out.append("/* the lifted loop at 0x%X up to its exit to 0x%X, the SPU registers as locals (see the tool) */\n" % (LOOP, EXIT))
    out.append("static void a8dec1_fused_6750(spu_context* ctx)\n{\n")
    for i in range(0, len(regs), 8):
        out.append("    u128 " + ", ".join("r%d = ctx->gpr[%d]" % (r, r) for r in regs[i:i + 8]) + ";\n")
    out.append("    goto L_%05X;\n" % LOOP)
    for line in g.lines:
        out.append(("%s\n" if line.endswith(":;") else "    %s\n") % line)
    out.append("L_exit:\n")
    for i in range(0, len(regs), 6):
        out.append("    " + " ".join("ctx->gpr[%d] = r%d;" % (r, r) for r in regs[i:i + 6]) + "\n")
    out.append("    ctx->image_id = ctx->module_img_a00 ? ctx->module_img_a00 : ctx->image_id;   /* as spu_img_restore after each call */\n")
    out.append("}\n#endif\n" + END)
    return "".join(out)


def main() -> int:
    arg = sys.argv[1] if len(sys.argv) > 1 else ""
    src = ROOT / "spu_jobs" / MOD / "spu_recomp.c"
    if not src.exists():
        print("no lifted module %s" % MOD)
        return 0
    raw = src.read_text(newline="")
    crlf = "\r\n" in raw
    text = raw.replace("\r\n", "\n")
    hook = HOOK.replace("@", MOD)
    hooked = BEGIN in text
    if hooked:                                        # take the hook out first; the rest works on the lifted text
        a, b = text.index(BEGIN), text.index(END) + len(END)
        text = text[:a] + text[b:]
        text = text.replace(hook, "", 1)
    funcs = functions(text, MOD)
    if LOOP not in funcs or body_hash(funcs, MOD, hook) != BODY_SHA256:
        print("module %s: not the reviewed lifted loop (sha256 %s)%s" % (
            MOD, body_hash(funcs, MOD, hook) if LOOP in funcs else "-", "; hooked" if hooked else ""))
        return 0 if arg == "--check" else 1
    if arg == "--check":
        print("module %s: %s" % (MOD, "hooked" if hooked else "not hooked"))
        return 0
    new = text
    if arg in ("", "--apply"):
        head_at = funcs[LOOP][0]
        head = text[head_at:text.index("\n", head_at) + 1]
        new = text[:head_at] + generate(funcs, MOD) + head + hook + text[head_at + len(head):]
    if new != raw.replace("\r\n", "\n"):
        src.write_text(new.replace("\n", "\r\n") if crlf else new, newline="")
    print("%s %s (hooked before: %s)" % ("restored" if arg == "--restore" else "applied", MOD, "yes" if hooked else "no"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
