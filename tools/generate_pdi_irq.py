"""Generate byte identities for the GT6 WWS IRQ native path; never modify game data."""
import argparse
import hashlib
from pathlib import Path
import struct
from game_paths import GAME

ROOT = Path(__file__).resolve().parents[1]
EXPECTED = 'd65b7e9c68b6eda6cb838d9d36de268d8ce248bdd4bc41e4c9f58b01b5ee19fd'
ap = argparse.ArgumentParser()
ap.add_argument('--check', action='store_true')
a = ap.parse_args()
elf = (GAME / 'EMAIN.ELF').read_bytes()
assert hashlib.sha256(elf).hexdigest() == EXPECTED, 'unrecognized EMAIN; keep interpreted fallback'
ea = 0x014EAA80 + 0x2C
phoff, = struct.unpack_from('>Q', elf, 0x20)
entsize, count = struct.unpack_from('>HH', elf, 0x36)
for i in range(count):
    pos = phoff + i * entsize
    typ, = struct.unpack_from('>I', elf, pos)
    off, va = struct.unpack_from('>QQ', elf, pos + 8)
    size, = struct.unpack_from('>Q', elf, pos + 0x20)
    if typ == 1 and va <= ea and ea + 0xC4 <= va + size:
        code = elf[off + ea - va:off + ea - va + 0xC4]
        break
else:
    raise ValueError('IRQ code is outside PT_LOAD')

def array(name, data):
    return ['static const unsigned char ' + name + '[' + str(len(data)) + '] = {'] + [
        '    ' + ','.join('0x%02x' % x for x in data[k:k+16]) + ','
        for k in range(0,len(data),16)] + ['};']

lines = ['/* Generated by tools/generate_pdi_irq.py from SHA256 ' + EXPECTED + '.',
         ' * LS A2C..AF0 is immutable code; runtime data below 16A0 is not registered. */',
         '#ifndef SPU_GT6_IRQ_CODE_H', '#define SPU_GT6_IRQ_CODE_H']
lines += array('spu_gt6_irq_code', code)
for name, op in [('save', 0x20800000), ('restore', 0x30800000)]:
    # Exact thunk emitted by the A60/AAC loops, including the four BI words.
    words = [op | (((0x3F9C0 + 16*r) >> 2) << 7) | r for r in range(76)]
    words += [0x35002780] * 4
    lines += array('spu_gt6_irq_' + name + '_code', struct.pack('>80I', *words))
lines += ['#endif', '']
text = '\n'.join(lines)
out = ROOT / 'ps3recomp/runtime/spu/spu_gt6_irq_code.h'
if a.check:
    assert out.read_text() == text, 'generated IRQ identity is stale'
else:
    out.write_text(text, encoding='utf-8', newline='\n')
print(('verified' if a.check else 'wrote'), out)
